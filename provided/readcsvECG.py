# ===================== Import packages ==============================
#
# The scipy.signal package is already imported, altough it is not used
# for the function os this program.
#

import numpy as np
import matplotlib.pyplot as plt
import pandas as pd
import scipy.signal as sig

# ===================== Ask for the datafile =========================
fid = input("What is the name of the data-file (.csv): ")

# ===================== Read the data ================================
#
# Use the package Pandas, since a lot of work is taken from you
# The result can be put in numpy arrays
# An excerpt of the data is printed to give you an impression of the data
#
data = pd.read_csv(fid, delimiter = ',')
df = pd.DataFrame(data)
print('An excerpt of the data is: \n',df)

# ===================== Set some parameters ===========================
#
# The Sample frequency is fixed to 1024/s
#
num = data.shape[0]                 # number of rows
fs = 1024.0
# ====================== Get the headers from the columns =============
#
chead = np.array(data.columns)

# ====================== put data in arrays ===========================
#
# From pandas DataFrame to arrays: use the names from the colums
# also make a time array. 
# Use the Headers from the index of the data-frame
#
t = np.linspace(0.,num/fs, num=num)
#z1 = data['ExG1'].values
#z2 = data['ExG2'].values
#z3 = data['ExG3'].values
#z4 = data['Pleth'].values

z1 = data[chead[2]].values
z2 = data[chead[3]].values
z3 = data[chead[4]].values
z4 = data[chead[5]].values

# ====================== Plot the result ==============================
rnum = 10240
plt.figure(figsize=(16,12))
plt.subplot(221)
plt.plot(t[0:rnum],z1[0:rnum])
plt.xlabel('t [s]')
plt.ylabel(r'%s [$\mu$V]'% chead[2])
plt.grid(True)
plt.subplot(222)
plt.plot(t[0:rnum],z2[0:rnum])
plt.xlabel('t [s]')
plt.ylabel(r'%s [$\mu$V]'% chead[3])
plt.grid(True)
plt.subplot(223)
plt.plot(t[0:rnum],z3[0:rnum])
plt.xlabel('t [s]')
plt.ylabel(r'%s [$\mu$V]'% chead[4])
plt.grid(True)
plt.subplot(224)
plt.plot(t[0:rnum],z4[0:rnum])
plt.xlabel('t [s]')
plt.ylabel(r'%s [arb. units]'% chead[5])
plt.grid(True)
plt.show()

